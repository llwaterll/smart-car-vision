#ifndef DRV_BATTERY_H
#define DRV_BATTERY_H

/*
 * ============================================================================
 * 文件名称：Drv_Battery.h
 * ============================================================================
 * 模块功能：电池供电电压采样。用 NEUQ 库的 ADC 驱动读一路分压后的电池
 *           电压，主循环每分钟更新一次，菜单在“蓝牙上位机”右侧显示。
 *
 *   外设资源：ADC1_IN10 / PC0（见 Board_Config.h 的 BOARD_BATTERY_ADC_CH）。
 *     PC0 在现有工程中空闲：不在编码器/电机/串口/按键/SPI Flash 上，
 *     也不是摄像头 SCCB（PC3/PC4/PC5）和 LCD（PB3/PB4/PB5）的引脚。
 *     电池必须经过分压再接入，PC0 绝对电压不得超过 3.3 V。
 *
 *   运行视角
 *     Battery_Init() ：配置 PC0 为模拟输入；
 *     Battery_Poll() ：主循环调用，每 BATTERY_POLL_MS 采样一次（8 次均值），
 *                      换算成电池端 mV 后写入快照；
 *     Battery_*()    ：给菜单快照提供只读结果。
 *
 *   分压比与校准
 *     BOARD_BATTERY_DIVIDER_X100 是“电池端 / ADC 端”的比值 ×100。
 *     例如 10 kΩ 上臂 + 2 kΩ 下臂时比值为 6.00，填 600；
 *     上电后用万用表量电池电压，按显示值微调该宏即可完成标定。
 * ============================================================================
 */

#include <stdint.h>

/* ---------------------------------------------------------------------------
 * 采样周期
 * 功能：两次电池采样的最小间隔，单位毫秒。
 * 取值：60000 ms = 1 分钟。电池电压变化慢，不需要更快；放在主循环里不会
 *       挤占 5 ms 控制节拍。
 * ------------------------------------------------------------------------- */
#define BATTERY_POLL_MS          60000U

/* ---------------------------------------------------------------------------
 * 均值滤波次数
 * 功能：每次采样连续转换的次数，取平均抑制电源纹波和 ADC 噪声。
 * 取值：8 次，总耗时约几十微秒。
 * ------------------------------------------------------------------------- */
#define BATTERY_FILTER_COUNT     8U

/*
 * 函数名称：Battery_Init
 * 函数功能：把电池采样引脚配置为模拟输入，并复位滤波结果。
 * 参数说明：无。
 * 返回参数：无。
 * 备注信息：必须在进入主循环前调用；不初始化时 ADC 读到的是浮空引脚。
 */
void Battery_Init(void);

/*
 * 函数名称：Battery_Poll
 * 函数功能：主循环调用；到 BATTERY_POLL_MS 时采样一次并更新电压快照。
 * 参数说明：now —— HAL_GetTick() 的毫秒时间。
 * 返回参数：无。
 * 备注信息：首次调用立即采样，之后每 60 s 一次；未到时间直接返回。
 */
void Battery_Poll(uint32_t now);

/*
 * 函数名称：Battery_Millivolts / Battery_Valid
 * 函数功能：读取最近一次电池电压 / 判断是否已经采到有效值。
 * 参数说明：无。
 * 返回参数：Battery_Millivolts 返回电池端电压，单位 mV；
 *           Battery_Valid 返回 1 表示已有采样结果。
 */
uint16_t Battery_Millivolts(void);
uint8_t  Battery_Valid(void);

#endif
