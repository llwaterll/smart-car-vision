#ifndef BOARD_CONFIG_H
#define BOARD_CONFIG_H

/*
 * ============================================================================
 * 文件名称：Board_Config.h
 * ============================================================================
 * 模块功能
 * ----------------------------------------------------------------------------
 * 整机板级基准。只放两类东西：
 *   1. 不属于任何单个外设、却被多个模块共用的量：控制节拍、串口通道分配；
 *   2. 整机满量程与安全限幅：PWM 满量程、转速满量程、90% 限幅、超速判据。
 *
 * 其它宏的分工（本文件不重复定义）：
 *   driver/Drv_Motor.h    电机 PWM 通道、方向引脚、前进电平、开关频率
 *   driver/Drv_Encoder.h  编码器定时器、引脚复用、每圈计数、输入滤波
 *   driver/Drv_Key.h      按键引脚、有效电平、消抖与连发时间
 *   driver/Drv_Lcd.h      屏幕行列数与样式
 *   driver/Drv_Gyro.h     陀螺仪采样周期与失效判定
 *   driver/Drv_Clock.h    1 MHz 控制时基
 *   driver/Drv_Uart.h     接收 FIFO 深度
 *   protocol/Proto_*.h    帧格式、命令号、协议超时
 *   pid/Pid.h             PID 增益、微分滤波、前馈模型、外环开关
 *   task/Task_Fsm.h       测速窗口、保护阈值、状态机时序上下限
 *   track/Track_Fsm.h     赛场几何、丢线降速、红绿灯停留
 *
 * 运行视角
 * ----------------------------------------------------------------------------
 *   上电后 User_Main() -> Car_Main()，用 BOARD_PERIOD_MS 启动 PIT_CH1；
 *   之后每 5 ms 进一次控制中断，全部闭环与保护都按这个节拍推进。
 * ============================================================================
 */

/* ---------------------------------------------------------------------------
 * 控制节拍
 *   外设：无（软件节拍，由 PIT_CH1 硬件定时器产生）
 *   功能：控制中断周期，测速窗口长度、PID 离散增益、各类超时都以它为单位
 *   取值：5 ms（200 Hz）。改动后必须重新整定 PID，并复核
 *         TASK_MIN_CONTROL_US / TASK_MAX_CONTROL_US 的允许范围。
 * ------------------------------------------------------------------------- */
#define BOARD_PERIOD_MS          5U       /* 控制中断周期，单位毫秒 */

/* ---------------------------------------------------------------------------
 * 串口通道分配
 *   外设：USART1（蓝牙 JDY-31，PA9 TX / PA10 RX）、UART4（视觉，PC10 TX / PC11 RX）
 *   功能：把“哪个串口干什么”固定在板级，避免上层各模块各写一份
 *   取值：蓝牙必须 0 号、视觉必须 3 号（NEUQ 库把 UART4 编为 UART_3）。
 *         下面用 #error 锁死：一旦误改，程序会把蓝牙帧当视觉帧解析，
 *         立刻死机式丢帧，必须编译期拦住。
 * ------------------------------------------------------------------------- */
#define BOARD_UART_BT_INDEX      0        /* 蓝牙串口在 NEUQ 库中的设备号 */
#define BOARD_UART_BT_BAUD       UART_BAUD_9600     /* 蓝牙波特率：JDY-31 默认 9600 */
#define BOARD_UART_VIS_INDEX     3        /* 视觉串口在 NEUQ 库中的设备号（UART4） */
#define BOARD_UART_VIS_BAUD      UART_BAUD_115200   /* 视觉波特率：与香橙派约定 115200 */
#ifndef BOARD_VISION_ENABLE
#define BOARD_VISION_ENABLE      1        /* 1=启用视觉串口；0=完全不初始化，用于纯蓝牙调试 */
#endif
#if BOARD_UART_BT_INDEX != 0 || BOARD_UART_VIS_INDEX != 3
#error This board requires UART_0 for Bluetooth and UART_3 for vision
#endif
#if BOARD_VISION_ENABLE != 0 && BOARD_VISION_ENABLE != 1
#error BOARD_VISION_ENABLE must be 0 or 1
#endif

/* ---------------------------------------------------------------------------
 * 上电自检开关
 *   外设：核心板 LED2（PA8）
 *   功能：1 = 不做任何外设初始化，只用忙等翻转 PA8，用于确认“独立上电
 *         时 MCU 到底跑没跑本固件”；0 = 正常启动。
 *   取值：正常 0；仅在排查上电不运行时临时改 1。
 * ------------------------------------------------------------------------- */
#define BOARD_LED_TEST           0        /* 1=只闪灯自检，0=正常启动 */

/* ---------------------------------------------------------------------------
 * 状态灯（高电平点亮）
 *   LED3 / PD8 ：心跳灯，主循环/控制中断每 500 ms 翻转一次；
 *   LED4 / PD10：按键提示灯，UP/DOWN/OK/BACK 分别闪 1~4 下，每下约 150 ms。
 *   取值：比赛主板固定，和原作者的 Car_Config 一致。
 * ------------------------------------------------------------------------- */
#define BOARD_HEARTBEAT_LED_PIN  PD8
#define BOARD_KEY_LED_PIN        PD10

/* ---------------------------------------------------------------------------
 * 电池电压采样
 *   外设：ADC1_IN10 / PC0
 *   功能：读取分压后的电池供电电压，主循环每分钟一次，菜单显示。
 *   取值：
 *     ADC 通道   PC0 在现有工程中空闲（不是电机/编码器/串口/按键/
 *                SPI Flash，也不是摄像头 SCCB 或 LCD 的引脚）。
 *     参考电压   3300 mV，即 MCU 的 VDDA。
 *     分压比     ×100 整数：600 表示 6.00。10 kΩ 上臂 + 2 kΩ 下臂为 6.00；
 *                其它电阻按 (R上 + R下) / R下 × 100 填写。
 *   注意：电池必须经分压后再接 PC0，引脚电压不得超过 3.3 V。
 *         第一次实车使用请用万用表量电池电压，按显示值微调该宏完成标定。
 * ------------------------------------------------------------------------- */
#define BOARD_BATTERY_ADC_CH       ADC1_CH10_PC0 /* 电池采样 ADC 通道 / 引脚 */
#define BOARD_BATTERY_VREF_MV      3300U         /* ADC 参考电压，mV */
#define BOARD_BATTERY_DIVIDER_X100 600U          /* 电池端/ADC 端分压比 ×100 */

/* ---------------------------------------------------------------------------
 * 板载 W25Q 片选
 *   外设：SPI Flash W25Q（PB0 = CS，PA5/PA6/PA7 与 SCK/MISO/MOSI 复用）
 *   功能：拉高后 Flash 不再驱动 MISO，PA5/PA6/PA7 才能安全用作右轮方向和
 *         编码器输入。上电必须最先拉高，且复用前再确认一次。
 *   取值：PB0，硬件固定，不可改。
 * ------------------------------------------------------------------------- */
#define BOARD_FLASH_CS           PB0      /* W25Q 片选引脚 */

/* ---------------------------------------------------------------------------
 * 整机满量程与安全限幅
 *   外设：无（纯数值口径，但被电机、PID、保护共同引用）
 *   功能：把“100% 占空比”和“空载最高转速”定义成唯一来源，限幅统一取
 *         满量程的 90%，给电池电压波动、测速噪声和闭环超调留 10% 余量。
 *   注意：限幅与超速判据必须同源，否则“允许给的目标”会高于“判超速的
 *         门限”，车会在正常行驶中被判故障。
 * ------------------------------------------------------------------------- */
#define BOARD_PWM_FULL           10000.0f /* PWM 满量程：NEUQ 库 PWM_MAX = 100% 占空比 */
#define BOARD_RPM_FULL           1000.0f  /* 转速满量程：电机空载转速，单位 rpm */
#define BOARD_LIMIT_FRACTION     0.90f    /* 安全限幅系数：满量程的 90% */
#define BOARD_RPM_LIMIT          (BOARD_RPM_FULL * BOARD_LIMIT_FRACTION) /* 900 rpm：转速指令上限 */
#define BOARD_PWM_LIMIT          (BOARD_PWM_FULL * BOARD_LIMIT_FRACTION) /* 9000：PWM 数值上限 */
#define BOARD_OVERSPEED_RPM      (BOARD_RPM_FULL * BOARD_LIMIT_FRACTION) /* 900 rpm：持续超过即判超速 */

/* ---------------------------------------------------------------------------
 * 故障处理模式
 *   功能：0 = 只记录并显示故障，不停车、不锁存；
 *         1 = 传统模式：锁存第一个故障、清输出并进入 CAR_FAULT，需 PE10 清除。
 *   注意：0 适合台架观察全部故障；赛道上有堵转/超速/方向接反继续驱动的风险。
 *         故障 7 的赛段 FAULT 仍由 Track_Fsm 执行任务级停车，不受本开关影响。
 * ------------------------------------------------------------------------- */
#ifndef CAR_FAULT_STOP_ENABLE
#define CAR_FAULT_STOP_ENABLE    0
#endif
#if CAR_FAULT_STOP_ENABLE != 0 && CAR_FAULT_STOP_ENABLE != 1
#error CAR_FAULT_STOP_ENABLE must be 0 or 1
#endif

/* ---------------------------------------------------------------------------
 * 故障降额（仅记录模式）
 *   功能：最近一次故障后把参考轮速最多下调该百分比，保持一段时间；
 *         多个故障不叠加，最低就是 (100 - PERCENT)%。清故障或停车后恢复。
 *   取值：当前 0 = 故障不降速，完全按目标轮速运行；改成 10 可恢复 10% 降额。
 *   注意：这是“参考转速”的降额，不是实测轮速的硬上限；堵转等物理故障
 *         仍可能使实测转速低于该值。
 * ------------------------------------------------------------------------- */
#define CAR_FAULT_DERATE_PERCENT 0U     /* 0=故障不降速；10=最多下调 10% */
#define CAR_FAULT_DERATE_HOLD_MS 1000U  /* 最近一次故障后保持降额的时长，毫秒 */
#if CAR_FAULT_DERATE_PERCENT > 100U
#error CAR_FAULT_DERATE_PERCENT must be 0..100
#endif

/* ---------------------------------------------------------------------------
 * 遥测分频（打包二进制帧，不再使用 JustFloat）
 *   外设：USART1（蓝牙，9600）
 *   快帧 A5：左/右实测 rpm + 状态，7 字节，每 2 拍 = 100 Hz（700 B/s）
 *   慢帧 A6：左/右位置（0.01 rev）+ 状态，7 字节，每 10 拍 = 20 Hz（140 B/s）
 *   合计 840 B/s，占 960 B/s 的 87.5%；若出现丢帧，把慢帧改成每 20 拍（10 Hz）。
 * ------------------------------------------------------------------------- */
#define BOARD_TELEMETRY_FAST_TICKS 2U     /* 快帧分频：2 × 5 ms = 100 Hz */
#define BOARD_TELEMETRY_SLOW_TICKS 10U    /* 慢帧分频：10 × 5 ms = 20 Hz */

#endif
